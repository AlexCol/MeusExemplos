EXECUTE BLOCK AS
BEGIN  
  IF (NOT(SELECT * FROM SP_EXISTE_TABLE('TB_SAP_INTEGRACAO_OPERACAO'))) THEN
  BEGIN
  	EXECUTE STATEMENT '
		CREATE TABLE TB_SAP_INTEGRACAO_OPERACAO (
		    ID BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
		    NOME VARCHAR(100) NOT NULL,
		    ENDPOINT VARCHAR(500) NOT NULL,
		    METODOHTTP VARCHAR(10) NOT NULL,
		    JSONDEFINICAO BLOB SUB_TYPE TEXT CHARACTER SET UTF8 NOT NULL,
		    VERSAO INTEGER DEFAULT 1 NOT NULL,
		    ATIVO BOOLEAN DEFAULT TRUE NOT NULL,
		
		    CONSTRAINT PK_SAP_INTEGRACAO_OPERACAO
		        PRIMARY KEY (ID),
		
		    CONSTRAINT UK_SAP_INTEGRACAO_OPERACAO_NOME
		        UNIQUE (NOME),
		
		    CONSTRAINT CK_INT_OPERATION_METHOD
		        CHECK (METODOHTTP IN (''GET'', ''POST'', ''PUT'', ''PATCH'', ''DELETE'')),
		
		    CONSTRAINT CK_INT_OPERATION_VERSION
		        CHECK (VERSAO > 0)
		);
	';

	EXECUTE STATEMENT '
		CREATE TABLE TB_SAP_INTEGRACAO_PENDENTES (
		    ID BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
		    IDOPERACAO BIGINT NOT NULL,
		    INPUTJSON BLOB SUB_TYPE TEXT CHARACTER SET UTF8 NOT NULL,
		    STATUS VARCHAR(20) DEFAULT ''PENDING'' NOT NULL,
		    TENTATIVAS INTEGER DEFAULT 0 NOT NULL,
		    DHCRIACAO TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
		    DHULTIMATENTATIVA TIMESTAMP,
		    DHENVIADO TIMESTAMP,
		    MENSAGEMERRO BLOB SUB_TYPE TEXT CHARACTER SET UTF8,
		    VERSAOOPERACAO INTEGER NOT NULL,
		
		    CONSTRAINT PK_SAP_INTEGRACAO_PENDENTES
		        PRIMARY KEY (ID),
		
		    CONSTRAINT FK_SAP_INTEGRACAO_PEND_OPERACAO
		        FOREIGN KEY (IDOPERACAO)
		        REFERENCES TB_SAP_INTEGRACAO_OPERACAO (ID),
		
		    CONSTRAINT CK_SAP_INTEGRACAO_PEND_STATUS
		        CHECK (STATUS IN (''PENDING'', ''PROCESSING'', ''SENT'', ''FAILED'')),
		
		    CONSTRAINT CK_SAP_INTEGRACAO_PEND_ATTEMPTS
		        CHECK (TENTATIVAS >= 0),
		
		    CONSTRAINT CK_SAP_INTEGRACAO_PEND_VERSION
		        CHECK (VERSAOOPERACAO > 0)
		);
	';
	
	EXECUTE STATEMENT 'CREATE INDEX IX_INTEGRACAO_STATUS_PENDENTES ON TB_SAP_INTEGRACAO_PENDENTES (STATUS, DHCRIACAO);';
	EXECUTE STATEMENT 'CREATE INDEX IX_INTEGRACAO_PENDENTES_OPERAC ON TB_SAP_INTEGRACAO_PENDENTES (IDOPERACAO, STATUS);';
	EXECUTE STATEMENT 'COMMENT ON TABLE TB_SAP_INTEGRACAO_OPERACAO IS ''Definicoes das operacoes disponiveis para integracao com o SAP'';';
	EXECUTE STATEMENT 'COMMENT ON COLUMN TB_SAP_INTEGRACAO_OPERACAO.JSONDEFINICAO IS ''Definicao da consulta e da montagem hierarquica do payload'';';
	EXECUTE STATEMENT 'COMMENT ON COLUMN TB_SAP_INTEGRACAO_OPERACAO.VERSAO IS ''Incrementado sempre que a definicao da operacao for alterada'';';
	EXECUTE STATEMENT 'COMMENT ON TABLE TB_SAP_INTEGRACAO_PENDENTES IS ''Fila de registros aguardando envio para o SAP'';';
	EXECUTE STATEMENT 'COMMENT ON COLUMN TB_SAP_INTEGRACAO_PENDENTES.VERSAOOPERACAO IS ''Versao da operacao no momento em que a pendencia foi criada'';';
  END
END;
         